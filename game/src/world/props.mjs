/** Полка-этажерка с книгами: стойки, три полки, корешки. */
P_.wallShelf = {
  name: 'полка',
  footprint: { w: 0.8, d: 0.18 },
  height: 0.7,
  tags: ['wall', 'storage', 'books'],
  parts: () => {
    const out = [
      B(0.03, 0.7, 0.17, -0.38, 0, 0, 'walnut'),
      B(0.03, 0.7, 0.17, 0.38, 0, 0, 'walnut'),
    ];
    for (const y of [0.02, 0.24, 0.46, 0.66]) out.push(B(0.79, 0.022, 0.18, 0, y, 0, 'oak'));
    // книги: разной высоты и цвета, вплотную друг к другу
    const colors = ['bookRed', 'bookBlue', 'bookGreen', 'bookBrown', 'paper'];
    for (let row = 0; row < 3; row++) {
      let x = -0.35;
      for (let i = 0; i < 9; i++) {
        const w = 0.026 + ((i * 7 + row * 3) % 5) * 0.006;
        const h = 0.16 + ((i * 5 + row) % 4) * 0.022;
        // корешки — острыми: фаска на 27 книжках стоит больше, чем вся
        // остальная полка, а разницы в кадре нет
        out.push(BX(w, h, 0.14, x + w / 2, 0.044 + row * 0.22, 0, colors[(i + row) % colors.length]));
        x += w + 0.004;
      }
    }
    return out;
  },
};

