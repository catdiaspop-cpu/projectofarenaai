// Библиотека предметов: чистые данные, никакого three.js.
// Примитивы описаны в локальных координатах предмета: (0,0) — центр основания,
// Y вверх, размеры в метрах. Сборщик сцены превратит их в геометрию.
//
// Такой формат даёт три вещи бесплатно: тесты геометрии без браузера,
// переиспользование предметов в разных комнатах, и возможность посчитать
// габариты и точки взаимодействия ещё до рендера.

/**
 * Коробка, стоит на высоте y0 — с фаской по рёбрам.
 *
 * Все предметы собираются из этих коробок, поэтому фаска здесь даёт сразу
 * всей мебели «мягкие» рёбра: свет ложится на скос, и параллелепипед
 * перестаёт читаться как картонный макет. Стоит это 44 треугольника вместо
 * 12 на деталь — на телефоне в кадре это единицы тысяч, незаметно.
 */
export const B = (w, h, d, x, y0, z, mat, extra = {}) => ({
  t: 'bev', s: [w, h, d], p: [x, y0 + h / 2, z], mat, ...extra,
});

/** Острые коробки — только для стекла, плёнок и плоских наклеек. */
export const BX = (w, h, d, x, y0, z, mat, extra = {}) => ({
  t: 'box', s: [w, h, d], p: [x, y0 + h / 2, z], mat, ...extra,
});

/** Цилиндр, стоит на высоте y0. */
export const C = (r, h, x, y0, z, mat, extra = {}) => ({
  t: 'cyl', r, r2: extra.r2 ?? r, h, p: [x, y0 + h / 2, z], mat, ...extra,
});

/** Шар. */
export const S = (r, x, y, z, mat, extra = {}) => ({
  t: 'sph', r, p: [x, y, z], mat, ...extra,
});

/** Конус, стоит на высоте y0. */
export const K = (r, h, x, y0, z, mat, extra = {}) => ({
  t: 'cone', r, h, p: [x, y0 + h / 2, z], mat, ...extra,
});

/** Наклонённая коробка (спинки, крышки). rot — радианы по X. */
export const BR = (w, h, d, x, y0, z, mat, rx = 0, extra = {}) => ({
  t: 'bev', s: [w, h, d], p: [x, y0 + h / 2, z], mat, rot: [rx, 0, 0], ...extra,
});

/** Плоский «блин» — ковёр, лужа, тень. */
export const P = (w, d, x, y, z, mat, extra = {}) => ({
  t: 'box', s: [w, 0.012, d], p: [x, y + 0.006, z], mat, flat: true, ...extra,
});

